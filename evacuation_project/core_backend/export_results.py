# Converts the finished scenario list into JSON or XML for the expert
# to download and use elsewhere. Both exports carry the same metadata
# (regulation source, timestamp, scenario count) so each file is
# self-contained and makes sense without any other context.

import json
from datetime import datetime
from xml.etree.ElementTree import Element, SubElement, tostring
from xml.dom.minidom import parseString

FIELDS = [
    "id", "description", "ifc_element_type", "ifc_element_name",
    "ifc_element_guid", "ifc_attribute", "regulation_id", "regulation_name",
    "regulation_description", "regulation_reference", "severity",
    "requires_manual_review", "ai_explanation"
]


def _export_metadata(scenarios, ai_model_used):
    return {
        "title":             "Evacuation Scenario Report",
        "regulation_source": "UK Approved Document B (Fire Safety)",
        "ai_model_used":     ai_model_used,
        "export_timestamp":  datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "total_scenarios":   len(scenarios),
        "note": (
            "Generated by EvacAI — MSc Dissertation prototype. Scenarios are "
            "AI-assisted suggestions for expert review and should not "
            "replace professional fire safety assessment."
        )
    }


def export_as_json(scenarios, ai_model_used="Unknown"):
    """Returns a formatted JSON string ready to write to a file or download."""
    output = {
        "export_info": _export_metadata(scenarios, ai_model_used),
        "scenarios": [
            {field: s.get(field) for field in FIELDS}
            for s in scenarios
        ]
    }
    return json.dumps(output, indent=2, ensure_ascii=False)


def export_as_xml(scenarios, ai_model_used="Unknown"):
    """Returns a formatted XML string ready to write to a file or download."""
    root = Element("EvacuationScenarios")
    root.set("regulationSource", "UK Approved Document B (Fire Safety)")
    root.set("aiModelUsed", ai_model_used)
    root.set("exportTimestamp", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    root.set("totalScenarios", str(len(scenarios)))

    for s in scenarios:
        node = SubElement(root, "Scenario",
                           id=str(s.get("id", "")),
                           severity=str(s.get("severity", "")))
        for field in FIELDS:
            if field in ("id", "severity"):
                continue
            child = SubElement(node, field)
            child.text = str(s.get(field, ""))

    return parseString(tostring(root, "unicode")).toprettyxml(indent="  ")


